import assert from "node:assert/strict";
import { parseScript, matchScriptSpeaker, ScriptPlayer } from "../runtime/script-player.js";
import { inferMessageMode } from "../runtime/message-routing.js";
assert.equal(inferMessageMode("大家一起讨论开源"), "discussion");
assert.equal(inferMessageMode("只让小明回答这个讨论问题"), "solo");
assert.equal(inferMessageMode("小明，你好"), "solo");
const script = parseScript("# 开场\n甲：你好\n乙: 收到:继续\n", "test.md");
assert.equal(script.lines.length, 2);
assert.equal(script.lines[1].text, "收到:继续");
assert.equal(parseScript('\ufeff{"lines":[{"speaker":"甲","text":"你好","state":"happy"}]}').lines[0].state, "happy");
assert.throws(() => parseScript("坏格式", "test.txt"));
assert.throws(() => parseScript('{"lines":[]}'));
assert.throws(() => parseScript(JSON.stringify({ lines: [{ speaker: "甲", text: "x".repeat(501) }] })));
assert.throws(() => parseScript(JSON.stringify({ lines: [{ speaker: "甲", text: "你好", state: "../secret" }] })));
const cast = [{ instanceId: "a", displayName: "甲-1", characterName: "甲", characterId: "char-a", enabled: true }];
assert.equal(matchScriptSpeaker("甲", cast), "a");
assert.equal(matchScriptSpeaker("CHAR-A", cast), "a");
assert.equal(matchScriptSpeaker("甲", [...cast, { ...cast[0], instanceId: "b" }]), "");
assert.equal(matchScriptSpeaker("甲", [{ ...cast[0], enabled: false }]), "");
const player = new ScriptPlayer();
const performed = [];
assert.equal(await player.play(script.lines, async (line) => performed.push(line.text)), 2);
assert.deepEqual(performed, ["你好", "收到:继续"]);
let release;
const blocked = player.play(script.lines, async () => new Promise((resolve) => { release = resolve; }));
await assert.rejects(player.play(script.lines, async () => {}));
player.stop(); release();
assert.equal(await blocked, 0);
assert.equal(player.running, false);
await assert.rejects(player.play(script.lines, async () => { throw new Error("missing state"); }));
assert.equal(player.running, false);
console.log("script-player: import, mapping, cancellation, no-overlap and error recovery passed");
